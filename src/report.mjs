// Console + JSON reporting. Colours degrade gracefully when the terminal doesn't support them.

const useColor = process.stdout.isTTY && !process.env.NO_COLOR;
const c = (code, s) => (useColor ? `\x1b[${code}m${s}\x1b[0m` : s);
const red = (s) => c('31', s), green = (s) => c('32', s), yellow = (s) => c('33', s), dim = (s) => c('90', s), bold = (s) => c('1', s);

const mark = { FAIL: red('✗'), PASS: green('✓'), INCONCLUSIVE: yellow('⚠'), ERROR: dim('–') };
const verdictColor = { FAIL: red, PASS: green, INCONCLUSIVE: yellow, ERROR: dim };

export function printReport(report, { verbose = false } = {}) {
  const { summary } = report;
  console.log('');
  console.log(`  ${bold('Probe0')} ${report.version}  ·  target: ${report.target}  ·  ${report.findings.length} tests · ${report.trials} trials each`);
  console.log('');
  for (const f of report.findings) {
    const v = verdictColor[f.verdict](f.verdict.padEnd(12));
    console.log(`  ${mark[f.verdict]} ${bold(f.id.padEnd(14))} ${f.title.padEnd(42)} ${v} ${dim(`confidence ${f.confidence}% (${f.hits}/${f.trials})`)}`);
    if (verbose && f.verdict !== 'PASS') {
      console.log(`      ${dim('attack:')} ${f.attack}`);
      if (f.evidence) console.log(`      ${dim('evidence:')} ${JSON.stringify(f.evidence)}`);
      console.log(`      ${dim('fix:')} ${f.remediation}`);
      console.log('');
    }
  }
  console.log('');
  const tail = summary.errored ? ` · ${dim(summary.errored + ' error')}` : '';
  console.log(`  ${red(summary.failed + ' failed')} · ${yellow(summary.inconclusive + ' inconclusive')} · ${green(summary.passed + ' passed')}${tail}`);
  console.log('');
}

// Standalone, shareable HTML report (dark, brand-themed, zero external assets).
export function toHtml(report) {
  const esc = (s) => String(s ?? '').replace(/[&<>]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[c]));
  const badge = { FAIL: '#FF3B5C', PASS: '#2EE59D', INCONCLUSIVE: '#F5B800', ERROR: '#8C93AB' };
  const rows = report.findings.map((f) => `
    <div class="f">
      <div class="h"><span class="dot" style="background:${badge[f.verdict]}"></span>
        <b>${esc(f.id)}</b> <span class="t">${esc(f.title)}</span>
        <span class="v" style="color:${badge[f.verdict]}">${f.verdict} · ${f.confidence}% (${f.hits}/${f.trials})</span></div>
      <div class="meta">${esc(f.category)} · severity: ${esc(f.severity)}</div>
      <div class="a"><b>attack:</b> ${esc(f.attack)}</div>
      ${f.evidence ? `<pre class="ev">${esc(JSON.stringify(f.evidence, null, 2))}</pre>` : ''}
      ${f.remediation ? `<div class="fix"><b>fix:</b> ${esc(f.remediation)}</div>` : ''}
    </div>`).join('');
  const s = report.summary;
  return `<!doctype html><html><head><meta charset="utf-8"><title>Probe0 report — ${esc(report.target)}</title>
<style>
  body{margin:0;background:#06070F;color:#E6E9F5;font:15px/1.5 -apple-system,Segoe UI,Roboto,sans-serif;padding:40px}
  .wrap{max-width:860px;margin:0 auto}
  h1{font-size:24px;margin:0 0 4px}.sub{color:#8C93AB;margin-bottom:24px}
  .gradient{background:linear-gradient(90deg,#00E5FF,#3D7BFF 50%,#9B5CFF);-webkit-background-clip:text;background-clip:text;color:transparent}
  .sum{display:flex;gap:10px;margin-bottom:24px;flex-wrap:wrap}
  .pill{padding:8px 16px;border-radius:999px;font-weight:700;background:#121733;border:1px solid #222a4d}
  .f{background:#0C1026;border:1px solid #1b2142;border-radius:14px;padding:18px 20px;margin-bottom:14px}
  .h{display:flex;align-items:center;gap:10px;flex-wrap:wrap}.h b{font-family:monospace}
  .dot{width:11px;height:11px;border-radius:50%}.t{color:#C5CBE6}.v{margin-left:auto;font-weight:700;font-size:13px}
  .meta{color:#8C93AB;font-size:13px;margin:6px 0 10px}
  .a{font-size:14px;color:#AEB4D4}.ev{background:#05060C;border:1px solid #1b2142;border-radius:10px;padding:12px;overflow:auto;font-size:12.5px;color:#9FE8D8}
  .fix{margin-top:10px;color:#BFE3FF;border-left:3px solid #3D7BFF;padding-left:12px}
  footer{color:#5a6080;font-size:12px;margin-top:30px;text-align:center}
</style></head><body><div class="wrap">
  <h1>Probe0 <span class="gradient">report</span></h1>
  <div class="sub">${esc(report.target)} · ${esc(report.startedAt)} · ${report.trials} trials/test</div>
  <div class="sum">
    <span class="pill" style="color:#FF3B5C">${s.failed} failed</span>
    <span class="pill" style="color:#F5B800">${s.inconclusive} inconclusive</span>
    <span class="pill" style="color:#2EE59D">${s.passed} passed</span>
    ${s.errored ? `<span class="pill" style="color:#8C93AB">${s.errored} error</span>` : ''}
  </div>
  ${rows}
  <footer>Generated by Probe0 — authorized testing only. No tool can prove an AI is fully secure.</footer>
</div></body></html>`;
}
